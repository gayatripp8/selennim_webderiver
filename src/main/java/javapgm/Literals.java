package javapgm;

public class Literals {

	public static void main(String[] args) {
		//"Java literals are fixed constant values assigned to variables directly in the code. 
		//Examples include integer, floating-point, character, string, boolean, and null literals."

		/*Important Points (Interview)
		Literals are constant values
		They are hardcoded in the program
		They do not change during execution
		*/
		byte age=29;
		int a=40;
		float b=90.87f;
		double c=23.45;
		char ch ='A';
		short sh=54;
		boolean s=true;
		long l=78965444L;
		
		System.out.println(l);
		
	}

}
